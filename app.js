// Stacked Deck State
let activeDeckCategory = 'all';
let currentDeckIndex = 0;
let filteredDeckProjects = [...portfolioProjects];
let isAnimatingDeck = false;

// Filter Projects for Deck
function getFilteredDeckProjects() {
  return activeDeckCategory === 'all'
    ? portfolioProjects
    : portfolioProjects.filter(p => p.category === activeDeckCategory);
}

// Update Deck HUD Counter & Progress Bar
function updateDeckHUD() {
  const total = filteredDeckProjects.length;
  if (!deckCounter || !deckProgressBar || total === 0) return;

  const currentNum = String(currentDeckIndex + 1).padStart(2, '0');
  const totalNum = String(total).padStart(2, '0');
  deckCounter.textContent = `${currentNum} / ${totalNum}`;

  const pct = ((currentDeckIndex + 1) / total) * 100;
  deckProgressBar.style.width = `${pct}%`;
}

// Update Category Buttons in Rail
function updateCategoryRailUI() {
  deckCategoryBtns.forEach(btn => {
    const cat = btn.getAttribute('data-category');
    if (cat === activeDeckCategory) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });
}

// Update Category Count Badges dynamically
function updateCategoryCounts() {
  const counts = {
    all: portfolioProjects.length,
    documentary: portfolioProjects.filter(p => p.category === 'documentary').length,
    'talking-head': portfolioProjects.filter(p => p.category === 'talking-head').length,
    sports: portfolioProjects.filter(p => p.category === 'sports').length,
    celebrity: portfolioProjects.filter(p => p.category === 'celebrity').length,
    animation: portfolioProjects.filter(p => p.category === 'animation').length,
    commercial: portfolioProjects.filter(p => p.category === 'commercial').length
  };

  deckCategoryBtns.forEach(btn => {
    const cat = btn.getAttribute('data-category');
    const countEl = btn.querySelector('.category-btn-count') || btn.querySelector('.category-count');
    if (countEl && counts[cat] !== undefined) {
      countEl.textContent = counts[cat];
    }
  });
}

