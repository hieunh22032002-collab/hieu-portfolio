// Mouse & Touch Drag Gestures for the Active Card
function bindDeckGestures(card) {
  let startX = 0;
  let startY = 0;
  let deltaX = 0;
  let deltaY = 0;
  let isDragging = false;
  const threshold = 75;

  function onPointerDown(e) {
    // Don't drag if clicking buttons, links, or video player
    if (e.target.closest('button') || e.target.closest('a') || e.target.closest('.video-poster-wrapper') || e.target.closest('.video-iframe-slot') || e.target.closest('iframe')) return;
    isDragging = true;
    startX = e.type.includes('touch') ? e.touches[0].clientX : e.clientX;
    startY = e.type.includes('touch') ? e.touches[0].clientY : e.clientY;
    deltaX = 0;
    deltaY = 0;
    card.classList.add('is-dragging');
  }

  function onPointerMove(e) {
    if (!isDragging) return;
    const currentX = e.type.includes('touch') ? e.touches[0].clientX : e.clientX;
    const currentY = e.type.includes('touch') ? e.touches[0].clientY : e.clientY;
    deltaX = currentX - startX;
    deltaY = currentY - startY;

    // Apply rotation & translation
    const rotate = deltaX * 0.05;
    card.style.transform = `translate3d(${deltaX}px, ${deltaY * 0.25}px, 0) rotate(${rotate}deg)`;
  }

  function onPointerUp() {
    if (!isDragging) return;
    isDragging = false;
    card.classList.remove('is-dragging');

    if (deltaX < -threshold) {
      nextDeckCard();
    } else if (deltaX > threshold) {
      prevDeckCard();
    } else {
      // Snap back
      card.style.transform = '';
    }
  }

  // Mouse events
  card.addEventListener('mousedown', onPointerDown);
  window.addEventListener('mousemove', onPointerMove);
  window.addEventListener('mouseup', onPointerUp);

  // Touch events
  card.addEventListener('touchstart', onPointerDown, { passive: true });
  window.addEventListener('touchmove', onPointerMove, { passive: true });
  window.addEventListener('touchend', onPointerUp);
}

// Attach Hover Scrubber to Active Card
function attachDeckHoverScrubber() {
  const activeCard = stackedDeckContainer.querySelector('.deck-card.is-active');
  if (!activeCard) return;

  const mediaContainer = activeCard.querySelector('.deck-video-hero');
  const scrubberBar = activeCard.querySelector('.video-scrubber-bar');
  const timecodeEl = activeCard.querySelector('.timecode-text');
  const durationDot = activeCard.querySelector('.duration-dot');
  const originalDuration = activeCard.getAttribute('data-duration') || '00:00';

  if (!mediaContainer || !scrubberBar || !timecodeEl) return;

  let animFrame = null;
  let startTime = null;
  const playDurationMs = 5000;
  let isManualScrub = false;

  let totalTargetSeconds = 60;
  const parts = originalDuration.split(':');
  if (parts.length === 2) {
    totalTargetSeconds = (parseInt(parts[0], 10) || 0) * 60 + (parseInt(parts[1], 10) || 0);
  }

  function formatTimecode(progress) {
    const currentSecs = progress * totalTargetSeconds;
    const mins = Math.floor(currentSecs / 60);
    const secs = Math.floor(currentSecs % 60);
    const frames = Math.floor(((currentSecs % 1) * 24));
    return `${String(mins).padStart(2, '0')}:${String(secs).padStart(2, '0')}:${String(frames).padStart(2, '0')}`;
  }

  function playLoop(timestamp) {
    if (!startTime) startTime = timestamp;
    const elapsed = timestamp - startTime;
    const progress = Math.min(1, (elapsed % playDurationMs) / playDurationMs);

    if (!isManualScrub) {
      scrubberBar.style.width = `${(progress * 100).toFixed(1)}%`;
      timecodeEl.textContent = formatTimecode(progress);
    }
    animFrame = requestAnimationFrame(playLoop);
  }

  mediaContainer.addEventListener('mouseenter', () => {
    startTime = null;
    isManualScrub = false;
    if (durationDot) durationDot.classList.remove('opacity-0');
    animFrame = requestAnimationFrame(playLoop);
  });

  mediaContainer.addEventListener('mousemove', (e) => {
    const rect = mediaContainer.getBoundingClientRect();
    const scrubPct = Math.max(0, Math.min(1, (e.clientX - rect.left) / rect.width));
    isManualScrub = true;
    scrubberBar.style.width = `${(scrubPct * 100).toFixed(1)}%`;
    timecodeEl.textContent = formatTimecode(scrubPct);
  });

  mediaContainer.addEventListener('mouseleave', () => {
    if (animFrame) cancelAnimationFrame(animFrame);
    isManualScrub = false;
    scrubberBar.style.width = '0%';
    timecodeEl.textContent = originalDuration;
    if (durationDot) durationDot.classList.add('opacity-0');
  });
}

