// 3D Ambient Kinetic Soundwave (Audio Frequencies / Timeline Flow)
function initHeroSoundwave() {
  const canvas = document.getElementById('hero-soundwave-canvas');
  if (!canvas || typeof THREE === 'undefined') return;

  const section = canvas.parentElement;
  let width = section.clientWidth;
  let height = section.clientHeight;

  const scene = new THREE.Scene();
  const camera = new THREE.PerspectiveCamera(45, width / height, 0.1, 1000);
  camera.position.set(0, 12, 42);

  let renderer;
  try {
    renderer = new THREE.WebGLRenderer({ canvas, alpha: true, antialias: true });
    renderer.setSize(width, height);
    renderer.setPixelRatio(Math.min(window.devicePixelRatio, 1.75));
  } catch (e) {
    console.warn('WebGL not supported for 3D soundwave', e);
    return;
  }

  // Soft circular glow texture for ambient film dust
  const particleCanvas = document.createElement('canvas');
  particleCanvas.width = 32;
  particleCanvas.height = 32;
  const pCtx = particleCanvas.getContext('2d');
  const pGrad = pCtx.createRadialGradient(16, 16, 0, 16, 16, 16);
  pGrad.addColorStop(0, 'rgba(252, 251, 248, 0.9)');
  pGrad.addColorStop(0.3, 'rgba(191, 63, 43, 0.4)');
  pGrad.addColorStop(0.7, 'rgba(35, 78, 56, 0.15)');
  pGrad.addColorStop(1, 'rgba(0, 0, 0, 0)');
  pCtx.fillStyle = pGrad;
  pCtx.fillRect(0, 0, 32, 32);
  const particleTexture = new THREE.CanvasTexture(particleCanvas);

  // 1. Multi-Track Timeline Ribbon Waves (Lightweight 120 FPS Optimized)
  const trackCount = 4;
  const pointsPerTrack = 45;
  const ribbons = [];

  for (let r = 0; r < trackCount; r++) {
    const positions = new Float32Array(pointsPerTrack * 3);
    const colors = new Float32Array(pointsPerTrack * 3);

    const geom = new THREE.BufferGeometry();
    geom.setAttribute('position', new THREE.BufferAttribute(positions, 3));
    geom.setAttribute('color', new THREE.BufferAttribute(colors, 3));

    // Distance from center determines opacity
    const distCenter = Math.abs(r - trackCount / 2) / (trackCount / 2);
    const opacity = (1 - distCenter * 0.4) * 0.35;

    const lineMat = new THREE.LineBasicMaterial({
      vertexColors: true,
      transparent: true,
      opacity: opacity,
      blending: THREE.NormalBlending
    });

    const line = new THREE.Line(geom, lineMat);
    scene.add(line);
    ribbons.push({ line, geom, r, zOffset: (r - trackCount / 2) * 5.0 });
  }

  // 2. Ambient Floating Dust Particles
  const particleCount = 28;
  const particleGeom = new THREE.BufferGeometry();
  const particlePos = new Float32Array(particleCount * 3);
  const particleInit = [];

  for (let i = 0; i < particleCount; i++) {
    const px = (Math.random() - 0.5) * 80;
    const py = -8 + Math.random() * 20;
    const pz = -12 + Math.random() * 30;
    particlePos[i * 3] = px;
    particlePos[i * 3 + 1] = py;
    particlePos[i * 3 + 2] = pz;
    particleInit.push({
      x: px, y: py, z: pz,
      speed: 0.008 + Math.random() * 0.012,
      phase: Math.random() * Math.PI * 2
    });
  }

  particleGeom.setAttribute('position', new THREE.BufferAttribute(particlePos, 3));
  const particleMat = new THREE.PointsMaterial({
    size: 1.5,
    map: particleTexture,
    transparent: true,
    opacity: 0.35,
    blending: THREE.NormalBlending,
    depthWrite: false
  });
  const particleSystem = new THREE.Points(particleGeom, particleMat);
  scene.add(particleSystem);

  // Mouse Parallax Interaction (Throttled & Subtle)
  let mouseX = 0;
  let mouseY = 0;
  window.addEventListener('mousemove', (e) => {
    mouseX = (e.clientX / window.innerWidth - 0.5) * 2;
    mouseY = (e.clientY / window.innerHeight - 0.5) * 2;
  }, { passive: true });

  // Visibility detection: Pause WebGL completely when scrolled past Hero
  let isHeroVisible = true;
  const heroObserver = new IntersectionObserver((entries) => {
    isHeroVisible = entries[0].isIntersecting;
  }, { threshold: 0.02 });
  heroObserver.observe(canvas);

  // Animation Loop (Zero Overhead when off-screen)
  let time = 0;
  function animate() {
    requestAnimationFrame(animate);
    if (!isHeroVisible) return; // 0% GPU / 0% CPU consumption when user scrolls down!

    time += 0.014;

    // Smooth camera sway
    camera.position.x += (mouseX * 2.5 - camera.position.x) * 0.03;
    camera.position.y += (12 + mouseY * 1.5 - camera.position.y) * 0.03;
    camera.lookAt(0, -2, 0);

    // Update Ribbon Tracks
    ribbons.forEach(({ geom, r, zOffset }) => {
      const pos = geom.attributes.position;
      const col = geom.attributes.color;

      for (let i = 0; i < pointsPerTrack; i++) {
        const x = (i / (pointsPerTrack - 1) - 0.5) * 110;
        const z = zOffset;

        const wave = Math.sin(x * 0.065 + time * 1.1 + r * 0.4) * 3.0
                   + Math.cos(x * 0.12 - time * 0.75 + r * 0.25) * 1.6;

        const y = -7.5 + wave;
        pos.setXYZ(i, x, y, z);

        const norm = (wave + 4.0) / 8.0;
        if (norm > 0.72) {
          col.setXYZ(i, 0.75, 0.25, 0.17);
        } else if (norm > 0.45) {
          col.setXYZ(i, 0.14, 0.31, 0.22);
        } else {
          col.setXYZ(i, 0.65, 0.55, 0.40);
        }
      }

      pos.needsUpdate = true;
      col.needsUpdate = true;
    });

    // Update Particles
    const pPos = particleGeom.attributes.position;
    for (let i = 0; i < particleCount; i++) {
      const p = particleInit[i];
      const curY = p.y + Math.sin(time + p.phase) * 1.2;
      const curX = p.x + Math.cos(time * 0.8 + p.phase) * 0.6;
      pPos.setXYZ(i, curX, curY, p.z);
    }
    pPos.needsUpdate = true;

    renderer.render(scene, camera);
  }
  animate();

  // Resize Listener
  window.addEventListener('resize', () => {
    width = section.clientWidth;
    height = section.clientHeight;
    camera.aspect = width / height;
    camera.updateProjectionMatrix();
    renderer.setSize(width, height);
  });
}

// Live Metric Numbers Counter
function initMetricCounters() {
  const counters = document.querySelectorAll('.metric-counter');
  if (!counters.length) return;

  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        const el = entry.target;
        const target = parseInt(el.getAttribute('data-target'), 10);
        const suffix = el.getAttribute('data-suffix') || '';
        const prefix = el.getAttribute('data-prefix') || '';
        const duration = 1400;
        const startTime = performance.now();

        function updateNumber(now) {
          const progress = Math.min((now - startTime) / duration, 1);
          const ease = progress === 1 ? 1 : 1 - Math.pow(2, -10 * progress);
          const current = Math.floor(ease * target);
          el.textContent = `${prefix}${current}${suffix}`;
          if (progress < 1) {
            requestAnimationFrame(updateNumber);
          } else {
            el.textContent = `${prefix}${target}${suffix}`;
          }
        }
        requestAnimationFrame(updateNumber);
        observer.unobserve(el);
      }
    });
  }, { threshold: 0.25 });

  counters.forEach(c => observer.observe(c));
}

